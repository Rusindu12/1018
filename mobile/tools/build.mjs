/* =====================================================================
   CryptoAI PRO — build.mjs
   Takes src/shell.html + src/js/*.js and produces ONE self-contained
   HTML file with every script inlined (no network needed to run it):

     • www/index.html      → what the Android APK ships
     • ../cryptoai.html    → the same file at the repo root, so the
                             GitHub Pages / Vercel site serves it too

   usage:  node tools/build.mjs            (or: npm run build)
   ===================================================================== */
import { readFileSync, writeFileSync, mkdirSync, statSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const ORDER = ['i18n.js', 'ta.js', 'patterns.js', 'brain.js', 'app.js', 'sysmgmt.js'];

const shellPath = join(root, 'src', 'shell.html');
const shell = readFileSync(shellPath, 'utf8');

/* ---- collect the sources ------------------------------------------- */
const parts = [];
for (const file of ORDER) {
  const p = join(root, 'src', 'js', file);
  const code = readFileSync(p, 'utf8');
  if (/<\/script/i.test(code)) throw new Error(`${file} contains a closing script tag — escape it`);
  parts.push({ file, code, bytes: Buffer.byteLength(code) });
}

/* ---- inline them ---------------------------------------------------- */
const tags = ORDER.map((f) => `<script src="${f}"></script>`).join('\n');
if (!shell.includes(tags)) {
  throw new Error('shell.html does not contain the expected script tag block:\n' + tags);
}

const banner = [
  '/* ------------------------------------------------------------------',
  '   CryptoAI PRO — single-file build',
  '   Generated by mobile/tools/build.mjs on ' + new Date().toISOString(),
  '   Do not edit this file: change mobile/src/shell.html or mobile/src/js/*.js',
  '   and run  npm run build  again.',
  '   Sources: ' + parts.map((p) => `${p.file} (${(p.bytes / 1024).toFixed(1)} KB)`).join(', '),
  '   ------------------------------------------------------------------ */'
].join('\n');

const inline =
  '<script>\n' +
  banner + '\n' +
  parts.map((p) => `/* ============================ ${p.file} ============================ */\n${p.code.trim()}`).join('\n\n') +
  '\n</script>';

/* NOTE: the replacement is passed as a function on purpose. A plain string
   replacement would interpret "$$", "$&", "$`" and "$'" inside the bundle as
   special patterns and silently corrupt the JavaScript. */
let out = shell.replace(tags, () => inline);

/* ---- PWA / install niceties (browser only; the APK is native) ------- */
const extraMeta = [
  '<meta name="mobile-web-app-capable" content="yes">',
  '<meta name="apple-mobile-web-app-capable" content="yes">',
  '<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">',
  '<meta name="apple-mobile-web-app-title" content="CryptoAI PRO">',
  '<meta name="description" content="CryptoAI PRO — offline-first crypto analysis, paper trading and an AI bot, in one file.">',
  '<link rel="icon" href="data:image/svg+xml,' +
  encodeURIComponent(
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="14" fill="#0a0e17"/>' +
    '<g fill="#f0b90b"><rect x="12" y="30" width="7" height="18" rx="2"/><rect x="24" y="22" width="7" height="26" rx="2"/><rect x="36" y="14" width="7" height="34" rx="2"/></g>' +
    '<circle cx="50" cy="16" r="6" fill="#8b5cf6"/><path d="M44 22l-4 6" stroke="#8b5cf6" stroke-width="3" stroke-linecap="round"/></svg>'
  ) +
  '">'
].join('\n');
out = out.replace('</head>', () => extraMeta + '\n</head>');

/* ---- write ---------------------------------------------------------- */
const wwwDir = join(root, 'www');
mkdirSync(wwwDir, { recursive: true });
const targets = [join(wwwDir, 'index.html'), resolve(root, '..', 'cryptoai.html')];
for (const t of targets) {
  writeFileSync(t, out, 'utf8');
  const kb = (statSync(t).size / 1024).toFixed(1);
  console.log('  ✓ ' + t.replace(resolve(root, '..', '..') + '/', '') + '  (' + kb + ' KB)');
}

const totalJs = parts.reduce((a, p) => a + p.bytes, 0);
console.log(
  '\n  shell ' + (Buffer.byteLength(shell) / 1024).toFixed(1) + ' KB + js ' + (totalJs / 1024).toFixed(1) +
  ' KB → ' + (Buffer.byteLength(out) / 1024).toFixed(1) + ' KB single file\n'
);
